import assert from 'node:assert/strict';
import {dispatchKeeperTool} from '../utils/keeperEvidence.ts';
import {keeperQueryReport} from '../utils/keeperQueryReport.ts';
const records=Array.from({length:65},(_,i)=>({id:`xml-r${i}`,artifactId:'xml',kind:'query',queryId:`q${i+1}`,line:i+1,text:`Question ${i+1}?`,source:'query',diagnostics:[],binding:i===1 ? {state:'conflicting',reason:'Wording differs.',response:'Must not appear'} : {state:'established',reason:'Strict match.',response:i===0?'Done':`Author answer ${i+1}`,pdfRecordId:`pdf-r${i}`}}));
const evidence={files:[{id:'xml',name:'article.xml',diagnostics:[]},{id:'pdf',name:'report.pdf',diagnostics:[]}],records:[...records,...records.map((r,i)=>({id:`pdf-r${i}`,artifactId:'pdf',kind:'pdf_query',page:i+1,text:'',source:'',diagnostics:[]}))]};
let offset=0;const seen=[];
do { const page=dispatchKeeperTool(evidence,'review_query_responses',{offset});seen.push(...page.records);offset=page.nextOffset; } while(offset!==null);
assert.equal(seen.length,65);assert.equal(new Set(seen.map(r=>r.id)).size,65);
assert.equal(seen[1].binding.response,undefined);
assert.ok(dispatchKeeperTool(evidence,'review_query_responses',{limit:41}).error);
assert.ok(dispatchKeeperTool(evidence,'review_query_responses',{path:'secret'}).error);
const report=keeperQueryReport(evidence);
for(let i=1;i<=65;i++)assert.match(report,new RegExp(`### q${i}\\b`));
assert.ok(!report.includes('Must not appear'));assert.match(report,/\*\*Edit status:\*\* Not established/);
assert.match(report,/Author response:\*\* Done/);
assert.match(report,/page 1;/);
const long={...evidence,records:[{...records[0],text:'x'.repeat(6000)}]};
assert.match(keeperQueryReport(long),/Excerpt truncated/);
const huge={...evidence,records:Array.from({length:101},(_,i)=>({...records[0],id:`q${i}`,queryId:`q${i}`}))};
assert.match(keeperQueryReport(huge),/showing 100 of 101/);
console.log('PASS 65-query batch coverage, strict binding, provenance, unknown edit status, validation, and explicit truncation');
