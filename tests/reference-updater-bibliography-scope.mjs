import assert from 'node:assert/strict';
import fs from 'node:fs';
import {engine,a,b,corrected} from './reference-updater-harness.mjs';
const parse=xml=>engine('','').parseReferences(xml);
const bibliography=xml=>`<ce:bibliography><ce:bibliography-sec>${xml}</ce:bibliography-sec></ce:bibliography>`;
const article=(body,refs)=>`<article><body>${body}</body><tail>${refs}</tail></article>`;
assert.deepEqual(parse(article(b,bibliography(a))).map(r=>r.id),['bb5']);
assert.deepEqual(parse(article(b,'')),[]);
assert.deepEqual(parse(article(b,bibliography(''))),[]);
assert.deepEqual(parse(a+b).map(r=>r.id),['bb5','bb10']);
assert.deepEqual(parse(`<ce:bibliography-sec>${a+b}</ce:bibliography-sec>`).map(r=>r.id),['bb5','bb10']);
assert.deepEqual(parse(bibliography(a)+b).map(r=>r.id),['bb5']);
assert.deepEqual(parse(bibliography(a)+bibliography(b)).map(r=>r.id),['bb5','bb10']);
assert.deepEqual(parse(article('<ce:section><ce:section-title>Uncited references</ce:section-title><ce:para><ce:cross-ref refid="bb5">[1]</ce:cross-ref></ce:para></ce:section>',bibliography(a))).map(r=>r.id),['bb5']);
const original=article(b,bibliography(a));
const updated=article(b,bibliography(corrected));
const state={scanResults:[]};engine(original,updated,state).runAnalysis();
assert.equal(state.scanResults.length,1);await engine(original,updated,state).initiateUpdate();
assert.ok(state.output.includes('Corrected Alpha evidence'));assert.ok(state.output.includes('Unrelated Beta study')); // Original body is preserved.
const absent={scanResults:[]};engine(original,article(b,''),absent).runAnalysis();
assert.deepEqual(absent.scanResults,[]);assert.ok(absent.toasts.some(t=>t.type==='error'&&t.msg.includes('must contain bibliography references')));
fs.mkdirSync('artifacts/reference-updater-bibliography-scope',{recursive:true});
fs.writeFileSync('artifacts/reference-updater-bibliography-scope/results.json',JSON.stringify([{name:'scoped-extraction',original,updated,output:state.output}],null,2));
console.log('10 bibliography scope scenarios passed.');
