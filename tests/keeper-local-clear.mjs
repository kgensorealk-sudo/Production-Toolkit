import 'fake-indexeddb/auto';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import {KeeperWorkspaceWriter,readKeeperTaskWorkspace,localTaskRecords} from '../utils/keeperLocalStore.ts';
import {keeperRestoredSources,keeperArtifactScope} from '../utils/keeperConversationScope.ts';
const artifacts=[{id:'xml',kind:'xml',name:'test.xml',content:'<article><opt_INS>New</opt_INS></article>'},{id:'pdf',kind:'pdf',name:'test_edit_report.pdf',content:'synthetic PDF'}];
await localTaskRecords('owner',{id:'task',artifacts});
const writer=new KeeperWorkspaceWriter('owner','task');
await writer.save({artifacts:[],activeScope:'[]',messages:[],inputPrompt:'',taskInstructions:''});
const saved=await readKeeperTaskWorkspace('owner','task');
const original=(await localTaskRecords('owner')).find(row=>row.id==='task');
const reopened=keeperRestoredSources(saved,original.artifacts);
assert.deepEqual(reopened.artifacts,artifacts);
assert.equal(reopened.activeScope,keeperArtifactScope(artifacts));
assert.deepEqual(saved.messages,[],'reopening must not revive cleared conversation');
await writer.save({...saved,...reopened});
assert.deepEqual(keeperRestoredSources(await readKeeperTaskWorkspace('owner','task')).artifacts,artifacts,'repaired task survives refresh');
const manual=[{id:'manual',kind:'xml',name:'manual.xml',content:'<article/>'}];
assert.deepEqual(keeperRestoredSources({artifacts:manual},artifacts).artifacts,manual,'manual workspace sources take precedence');
assert.deepEqual(keeperRestoredSources(undefined).artifacts,[]);
const ui=fs.readFileSync('components/KeeperSandbox.tsx','utf8');
const reset=ui.slice(ui.indexOf('const executeResetChat'),ui.indexOf('const handleSkipTyping'));
assert.ok(reset.includes('setMessages([])'));
assert.ok(!reset.includes('setSandboxArtifacts([])'));
assert.ok(!reset.includes('setEvidenceReport(null)'));
assert.ok(reset.includes('keeperArtifactScope(sandboxArtifacts)'));
console.log('PASS clear retains files/findings, legacy empty task reopens with matching source scope, cleared history stays cleared, repair persists, and manual sources remain intact');
