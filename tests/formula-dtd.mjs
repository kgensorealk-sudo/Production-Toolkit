import assert from 'node:assert/strict';
import fs from 'node:fs';
import {JSDOM} from 'jsdom';
import {canonicalFormulaXml, formulaAttributeIssues, validateFormulaDtd, validatedFormulaXml} from '../utils/formulaDtd.ts';
import {testOutputPath} from './test-output.mjs';

const dom=new JSDOM('');
for(const name of ['document','DOMParser','XMLSerializer'])globalThis[name]=dom.window[name];
const cases=[], native=[];
const add=(name,xml,valid)=>cases.push({name,xml,valid});
const page=fs.readFileSync('pages/FormulaEditorExperimental.tsx','utf8');
for(const [i,match] of [...page.matchAll(/xml: `([\s\S]*?)`/g)].entries())add('preset '+i,match[1],true);
add('bare MathML','<math><mi>x</mi></math>',true);
add('alternative prefix','<m:math xmlns:m="http://www.w3.org/1998/Math/MathML"><m:mi>x</m:mi></m:math>',true);
add('fraction','<math><mfrac><mi>a</mi><mi>b</mi></mfrac></math>',true);
add('fraction one operand','<math><mfrac><mi>a</mi></mfrac></math>',false);
add('fraction three operands','<math><mfrac><mi>a</mi><mi>b</mi><mi>c</mi></mfrac></math>',false);
add('script missing operand','<math><msubsup><mi>a</mi><mi>b</mi></msubsup></math>',false);
add('script correct order','<math><msubsup><mi>a</mi><mi>b</mi><mi>c</mi></msubsup></math>',true);
add('empty spacing','<math><mspace width="1em"/></math>',true);
add('spacing with text','<math><mspace>z</mspace></math>',false);
add('spacing with whitespace','<math><mspace> </mspace></math>',false);
add('empty delimiters','<math><mfenced open="" close="" separators=""><mi>x</mi><mi>y</mi></mfenced></math>',true);
add('fence color','<math><mfenced mathcolor="red"><mi>x</mi></mfenced></math>',true);
add('fence mathsize is not declared','<math><mfenced mathsize="2em"><mi>x</mi></mfenced></math>',false);
add('invalid attribute','<math><mi invented="x">a</mi></math>',false);
add('invalid mathvariant','<math><mi mathvariant="nonsense">a</mi></math>',false);
add('font variant on number','<math><mn mathvariant="bold">2</mn></math>',true);
add('invalid boolean enumeration','<math><mo stretchy="yes">(</mo></math>',false);
add('valid boolean enumeration','<math><mo stretchy="true">(</mo></math>',true);
add('invalid node','<math><invented>a</invented></math>',false);
add('invalid hidden annotation','<math><semantics><mi>x</mi><annotation-xml><invented/></annotation-xml></semantics></math>',false);
add('duplicate ID','<math><mi id="x">x</mi><mi id="x">y</mi></math>',false);
add('invalid ID','<math><mi id="has spaces">x</mi></math>',false);
add('Unicode ID','<math><mi id="α">x</mi></math>',true);
add('label ordering','<ce:formula><ce:label>(1)</ce:label><mml:math><mml:mi>x</mml:mi></mml:math></ce:formula>',true);
add('bad label ordering','<ce:formula><mml:math><mml:mi>x</mml:mi></mml:math><ce:label>(1)</ce:label></ce:formula>',false);
add('display multiple formulas','<ce:display><ce:formula><mml:math/></ce:formula><ce:formula><mml:math/></ce:formula></ce:display>',false);
add('escaping and CDATA','<math><mtext><![CDATA[ a < b & c\nd ]]></mtext></math>',true);
add('DTD character entities','<math><mi>&alpha;</mi><mo>&NotEqualTilde;</mo><mtext>&nbsp;</mtext></math>',true);
add('entity syntax in literal CDATA','<math><mtext><![CDATA[&unknown; &alpha;]]></mtext></math>',true);
add('new CE 5.7 color','<math><mtext><ce:color name="red">x</ce:color></mtext></math>',version=>version==='5.7');
add('required CE color attribute','<math><mtext><ce:color>x</ce:color></mtext></math>',false);
let checks=0;
for(const version of ['5.6','5.7'])for(const entry of cases){
    const expected=typeof entry.valid==='function'?entry.valid(version):entry.valid;
    const result=validateFormulaDtd(entry.xml,version);
    assert.equal(result.valid,expected,`${version} ${entry.name}: ${result.errors.join('; ')}`);
    if(expected)assert.ok(validatedFormulaXml(entry.xml,version));
    else assert.throws(()=>validatedFormulaXml(entry.xml,version));
    if(result.canonicalXml)native.push({name:entry.name,version,output:result.canonicalXml,expectedValid:expected});
    checks++;
}
for(const xml of ['<math><mi>x</math>','<!DOCTYPE math SYSTEM "https://invalid.test/dtd"><math/>','<!ENTITY x SYSTEM "file:///secret"><math/>','<mml:math xmlns:mml="urn:wrong"/>','<math/><math/>','<math><mi>&unknown;</mi></math>']){
    assert.equal(validateFormulaDtd(xml,'5.7').valid,false);checks++;
}
assert.throws(()=>validatedFormulaXml('<math/>',''),/Select the destination/);
assert.equal(validateFormulaDtd('<math/>','invalid').valid,false);
assert.ok(formulaAttributeIssues('5.7','mml:mfenced',{mathsize:'2em'}).length);
assert.equal(formulaAttributeIssues('5.7','mml:mfenced',{open:'[',close:']',separators:';'}).length,0);
const refs=validateFormulaDtd('<math><mi xref="article-id">x</mi></math>','5.7');
assert.equal(refs.valid,true);assert.ok(refs.warnings.some(message=>message.includes('article-id')));
const resolved=validateFormulaDtd('<math><mi id="a">x</mi><mi xref="a">y</mi></math>','5.7');
assert.equal(resolved.valid,true);assert.equal(resolved.warnings.length,0);
assert.equal(canonicalFormulaXml('<m:math xmlns:m="http://www.w3.org/1998/Math/MathML"><m:mi> x </m:mi></m:math>').includes('<mml:mi> x </mml:mi>'),true);
assert.ok(canonicalFormulaXml('<math><mi>&alpha;</mi></math>').includes('α'));
assert.ok(canonicalFormulaXml('<math><mtext>&amp;alpha;</mtext></math>').includes('&amp;alpha;'));
const copied=validatedFormulaXml('<ce:formula id="fo1"><mml:math altimg="si2.svg"><mml:mi>x</mml:mi></mml:math></ce:formula>','5.7');
assert.ok(!copied.includes('xmlns'));
assert.ok(copied.includes('altimg="si2.svg"'));
assert.equal(validateFormulaDtd(copied,'5.7').valid,true);
const path=testOutputPath('formula-dtd/native-cases.json');fs.writeFileSync(path,JSON.stringify(native,null,2));
console.log(`PASS ${checks} versioned formula DTD cases and export/context checks.`);
console.log(`Native cases: ${path}`);
dom.window.close();
